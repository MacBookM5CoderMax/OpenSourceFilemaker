import { test, describe, before, after } from 'node:test';
import assert from 'node:assert/strict';
import { PostgresClient } from '../src/ess/postgres.ts';
import { MysqlDriver } from '../src/ess/mysql.ts';
import { TdsClient } from '../src/ess/tds.ts';
import { EssConflict, writeEssBatch, writeEssRow, type SqlDriver, type SqlValue } from '../src/ess/driver.ts';

// Real-server conformance for the outside SQL clients. It runs only when TABULARIUS_ESS_REAL names the databases
// to test (comma separated: postgresql, mysql, mariadb, sqlserver) and `scripts/ess-real-db/run.sh` has started them.
// Without that variable every case is skipped, so `npm run test:ci` stays offline. The same cases run against every
// database: what differs is only the table definition, the way to sleep and the way to count.

const wanted = new Set((process.env.TABULARIUS_ESS_REAL ?? '').split(',').map((s) => s.trim().toLowerCase()).filter(Boolean));
const host = process.env.TABULARIUS_ESS_REAL_HOST ?? '127.0.0.1';
const port = (name: string, fallback: number) => Number(process.env[`TABULARIUS_ESS_REAL_${name}_PORT`] ?? fallback);
const password = 'Ess-Test-1-aA';

interface Profile {
  id: string;
  dialect: SqlDriver['dialect'];
  connect(over?: { password?: string; tls?: 'verify-full' | 'require' | 'disable'; noCa?: boolean }): Promise<SqlDriver>;
  /** Drop and create the test table `ess_t` (the key is `id`, generated by the database) and fill it with `n` rows when asked. */
  ddl: string[];
  sleep: string;
  series(n: number): string;
  /** A statement to run once per connection before `series`. */
  prepare?: string;
  /** TLS the server offers out of the box, to check the three modes. */
  tls: boolean;
}

const ca = (name: string, o?: { noCa?: boolean }) => o?.noCa ? undefined : process.env[`TABULARIUS_ESS_REAL_${name}_CA`];

const profiles: Profile[] = [
  {
    id: 'postgresql', dialect: 'postgresql', tls: true,
    connect: (o) => PostgresClient.connect({ host, port: port('POSTGRESQL', 55432), user: 'ess', database: 'ess', password: o?.password ?? password,
      sslmode: o?.tls ?? 'verify-full', ca: ca('POSTGRESQL', o), connectTimeoutMs: 20_000 }),
    ddl: ['DROP TABLE IF EXISTS ess_t',
      `CREATE TABLE ess_t (id serial PRIMARY KEY, name text NOT NULL, qty integer, price numeric(12,2), ratio double precision,
        born date, at_time time, stamp timestamp, flag boolean, bin bytea, note text, big bigint)`],
    sleep: 'SELECT pg_sleep(10)',
    series: (n) => `SELECT g FROM generate_series(1, ${n}) g`,
  },
  ...(['mysql', 'mariadb'] as const).map((id): Profile => ({
    id, dialect: 'mysql', tls: id === 'mysql',
    connect: (o) => MysqlDriver.connect({ host, port: port(id.toUpperCase(), id === 'mysql' ? 53306 : 53307), user: 'ess', database: 'ess',
      password: o?.password ?? password, tls: o?.tls ?? (id === 'mysql' ? 'verify-ca' : 'disable'), ca: ca(id.toUpperCase(), o),
      allowInsecure: (o?.tls ?? (id === 'mysql' ? 'verify-ca' : 'disable')) === 'disable', connectTimeoutMs: 20_000 }),
    ddl: ['DROP TABLE IF EXISTS ess_t',
      `CREATE TABLE ess_t (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, qty INT, price DECIMAL(12,2), ratio DOUBLE,
        born DATE, at_time TIME, stamp DATETIME(6), flag TINYINT(1), bin BLOB, note TEXT, big BIGINT) DEFAULT CHARSET utf8mb4`],
    sleep: 'SELECT SLEEP(10)',
    prepare: id === 'mysql' ? 'SET SESSION cte_max_recursion_depth = 100000' : 'SET SESSION max_recursive_iterations = 100000',
    series: (n) => `WITH RECURSIVE s(n) AS (SELECT 1 UNION ALL SELECT n + 1 FROM s WHERE n < ${n}) SELECT n FROM s`,
  })),
  {
    id: 'sqlserver', dialect: 'sqlserver', tls: true,
    connect: (o) => TdsClient.connect({ host, port: port('SQLSERVER', 51433), user: 'sa', database: 'ess', password: o?.password ?? password,
      encryption: o?.tls === 'disable' ? 'disable' : 'mandatory', allowUnencrypted: o?.tls === 'disable',
      trustServerCertificate: o?.tls === 'require', ca: o?.tls === 'require' ? undefined : ca('SQLSERVER', o), timeoutMs: 20_000 }),
    ddl: ['DROP TABLE IF EXISTS ess_t',
      `CREATE TABLE ess_t (id INT IDENTITY PRIMARY KEY, name NVARCHAR(100) NOT NULL, qty INT, price DECIMAL(12,2), ratio FLOAT,
        born DATE, at_time TIME, stamp DATETIME2, flag BIT, bin VARBINARY(MAX), note NVARCHAR(MAX), big BIGINT)`],
    sleep: "WAITFOR DELAY '00:00:10'",
    prepare: undefined,
    series: (n) => `WITH s(n) AS (SELECT 1 UNION ALL SELECT n + 1 FROM s WHERE n < ${n}) SELECT n FROM s OPTION (MAXRECURSION 0)`,
  },
];

const num = (v: SqlValue | undefined) => v === null || v === undefined ? v : Number(v);

for (const profile of profiles) {
  const skip = wanted.has(profile.id) ? false : `set TABULARIUS_ESS_REAL=${profile.id} and start the database with scripts/ess-real-db/run.sh`;
  describe(`real ${profile.id}`, { skip, concurrency: false }, () => {
    let db: SqlDriver;
    before(async () => {
      db = await profile.connect();
      for (const statement of profile.ddl) await db.query(statement, []);
    });
    after(async () => { await db?.close(); });

    const reset = async () => { await db.query('DELETE FROM ess_t', []); };
    const all = async () => (await db.query('SELECT id, name, qty, price, ratio, born, at_time, stamp, flag, note, big FROM ess_t ORDER BY id', [])).rows;
    const table = { name: 'ess_t' };

    test('answers a query and names its columns', async () => {
      const result = await db.query(profile.series(3), []);
      assert.deepEqual(result.rows.map((r) => num(r[0])), [1, 2, 3]);
    });

    test('lists the table, its columns, their types and the key', async () => {
      const tables = await db.tables();
      assert.ok(tables.some((t) => t.name.toLowerCase() === 'ess_t'), `ess_t is listed (got ${tables.map((t) => t.name).join(', ')})`);
      const columns = await db.columns(table);
      assert.deepEqual(columns.map((c) => c.name), ['id', 'name', 'qty', 'price', 'ratio', 'born', 'at_time', 'stamp', 'flag', 'bin', 'note', 'big']);
      assert.deepEqual(columns.filter((c) => c.key).map((c) => c.name), ['id']);
      assert.equal(columns.find((c) => c.name === 'name')!.nullable, false);
      assert.equal(columns.find((c) => c.name === 'qty')!.nullable, true);
      assert.ok(columns.every((c) => c.type), 'every column has a type');
    });

    test('creates a row with a generated key and reads every type back', async () => {
      await reset();
      const created = await writeEssRow(db, { kind: 'create', table: 'ess_t', keys: ['id'], values: {
        name: 'Zoë ✓ 你好 😀', qty: 42, price: 1234.5, ratio: 0.1, born: '2024-02-29', at_time: '13:45:07', stamp: '2024-02-29 13:45:07.123456',
        flag: 1, note: "it's a \"quote\" and a \\ backslash", big: 9007199254740993n } });
      assert.equal(created.keys?.length, 1);
      assert.ok(Number(created.keys![0]) >= 1, 'a key came back');
      const [row] = await all();
      assert.equal(num(row[0]), Number(created.keys![0]));
      assert.equal(row[1], 'Zoë ✓ 你好 😀');
      assert.equal(num(row[2]), 42);
      assert.equal(num(row[3]), 1234.5);
      assert.equal(num(row[4]), 0.1);
      assert.match(String(row[5]), /^2024-02-29/);
      assert.match(String(row[6]), /^13:45:07/);
      assert.match(String(row[7] instanceof Date ? row[7].toISOString() : row[7]), /2024-02-29[T ]13:45:07/);
      assert.ok(row[8] === true || row[8] === 1 || row[8] === 1n || row[8] === '1', `flag reads back true (got ${String(row[8])})`);
      assert.equal(row[9], "it's a \"quote\" and a \\ backslash");
      assert.equal(String(row[10]), '9007199254740993', 'a bigint past 2^53 keeps every digit');
    });

    test('NULLs round-trip and a NULL column does not stop an edit', async () => {
      await reset();
      const created = await writeEssRow(db, { kind: 'create', table: 'ess_t', keys: ['id'], values: { name: 'n', qty: null } });
      const id = Number(created.keys![0]);
      let [row] = await all();
      assert.equal(row[2], null);
      await writeEssRow(db, { kind: 'edit', table: 'ess_t', keys: ['id'], values: { qty: 7 }, before: { id, name: 'n', qty: null } });
      [row] = await all();
      assert.equal(num(row[2]), 7);
    });

    test('an edit of a row that changed after it was read is a conflict, and a delete removes the row', async () => {
      await reset();
      const created = await writeEssRow(db, { kind: 'create', table: 'ess_t', keys: ['id'], values: { name: 'before', qty: 1 } });
      const id = Number(created.keys![0]);
      await db.query('UPDATE ess_t SET qty = 2', []);
      await assert.rejects(writeEssRow(db, { kind: 'edit', table: 'ess_t', keys: ['id'], values: { name: 'mine' }, before: { id, name: 'before', qty: 1 } }), EssConflict);
      const removed = await writeEssRow(db, { kind: 'delete', table: 'ess_t', keys: ['id'], values: {}, before: { id } });
      assert.equal(removed.deleted, true);
      assert.equal((await all()).length, 0);
    });

    test('a batch is one transaction: a failing write undoes the writes before it', async () => {
      await reset();
      await assert.rejects(writeEssBatch(db, [
        { kind: 'create', table: 'ess_t', keys: ['id'], values: { name: 'first' } },
        { kind: 'create', table: 'ess_t', keys: ['id'], values: { name: null } }, // NOT NULL
      ]));
      assert.equal((await all()).length, 0, 'the first row was rolled back');
      const ok = await writeEssBatch(db, [
        { kind: 'create', table: 'ess_t', keys: ['id'], values: { name: 'a' } },
        { kind: 'create', table: 'ess_t', keys: ['id'], values: { name: 'b' } },
      ]);
      assert.equal(ok.length, 2);
      assert.equal((await all()).length, 2);
    });

    test('the row limit stops a result that is too large', async () => {
      // PostgreSQL marks the result truncated (the bridge turns that into the row-limit error); the others throw the row-limit message.
      const own = await profile.connect();
      try {
        const outcome = await own.query(profile.series(500), [], { maxRows: 100 }).then((r) => r, (e: Error) => e);
        if (outcome instanceof Error) assert.match(outcome.message, /^(Error: )?SQL row limit of 100 exceeded/);
        else assert.equal((outcome as { truncated?: boolean }).truncated, true, 'a result over the limit is refused or marked truncated');
      } finally { await own.close(); }
      const after = await profile.connect();
      try { assert.equal((await after.query(profile.series(5), [])).rows.length, 5, 'a new connection works'); } finally { await after.close(); }
    });

    test('a large result arrives whole', async () => {
      if (profile.prepare) await db.query(profile.prepare, []);
      const result = await db.query(profile.series(20_000), [], { maxRows: 100_000 });
      assert.equal(result.rows.length, 20_000);
      assert.equal(num(result.rows[19_999][0]), 20_000);
    });

    test('a query that outlasts its timeout is cancelled and the connection is usable again', async () => {
      const own = await profile.connect();
      const started = Date.now();
      try { await assert.rejects(own.query(profile.sleep, [], { timeoutMs: 1000 })); } finally { await own.close(); }
      assert.ok(Date.now() - started < 8000, `gave up in ${Date.now() - started} ms, long before the 10 s sleep ended`);
      const again = await profile.connect();
      try { assert.equal((await again.query(profile.series(1), [])).rows.length, 1); } finally { await again.close(); }
      // The database itself stopped the sleeping statement, rather than leaving it to run its ten seconds.
      await new Promise((resolve) => setTimeout(resolve, 500));
    });

    test('a wrong password is refused and the message does not repeat it', async () => {
      const bad = ['wrong', 'password', 'x'].join('-');
      await assert.rejects(profile.connect({ password: bad }), (e: unknown) => {
        assert.ok(e instanceof Error);
        assert.ok(!e.message.includes(bad), 'the password is not in the message');
        return true;
      });
    });

    test('quotes in names and values cannot change the statement', async () => {
      await reset();
      const hostile = "x'); DROP TABLE ess_t; --";
      await writeEssRow(db, { kind: 'create', table: 'ess_t', keys: ['id'], values: { name: hostile } });
      assert.equal((await all())[0][1], hostile);
      assert.equal(db.quoteName('a"b`c]d').length > 0, true);
    });

    if (profile.tls) {
      test('TLS: the default refuses a server whose certificate it was not given', async () => {
        await assert.rejects(profile.connect({ noCa: true }), (e: unknown) => {
          assert.ok(e instanceof Error);
          assert.ok(!e.message.includes(password), 'the password is not in the message');
          return true;
        });
      });
      test('TLS: the default verifies the server certificate it was given', async (t) => {
        if (!process.env[`TABULARIUS_ESS_REAL_${profile.id.toUpperCase()}_CA`]) return t.skip('the runner supplies no certificate for this database');
        const c = await profile.connect();
        try { assert.equal((await c.query(profile.series(1), [])).rows.length, 1); } finally { await c.close(); }
      });
      test('TLS: require encrypts without verifying', async () => {
        const c = await profile.connect({ tls: 'require' });
        try { assert.equal((await c.query(profile.series(1), [])).rows.length, 1); } finally { await c.close(); }
      });
    }
  });
}

test('the real-database cases are skipped unless named', { skip: wanted.size > 0 && 'real databases are being tested' }, () => {
  assert.equal(wanted.size, 0);
});
